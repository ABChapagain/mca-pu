# List operations
numbers = [10, 20, 30]
numbers.append(40)
numbers.remove(20)
print('List:', numbers)
print('First element:', numbers[0])
# Tuple operations
marks = (80, 75, 90, 85)
print('Tuple:', marks)
print('Maximum marks:', max(marks))
print('Length of tuple:', len(marks))
# Dictionary operations
student = {'name': 'Achyut', 'age': 24, 'course': 'MCA'}
student['semester'] = 2
student['age'] = 24
print('Dictionary:', student)
print('Student name:', student['name'])